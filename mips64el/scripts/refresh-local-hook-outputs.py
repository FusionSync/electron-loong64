#!/usr/bin/env python3
"""Ensure local Chromium DEPS version-hook outputs, without network access.

Valid cached files are retained, including their mtimes, even when a copied
checkout has no readable Git metadata. Repair requires the original Git repos.
Only the four lastchange.py hooks run; this does not run all gclient hooks.
"""

import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile


ROOT = Path(__file__).resolve().parents[1]
REVISION = r"([0-9a-f]{40})(?:-[^\s]+)?"


def read(path):
    try:
        return path.read_text()
    except (OSError, UnicodeError):
        return ""


def expected_revisions(source):
    pins = json.loads((ROOT / "metadata/source-pins.json").read_text())
    deps = read(source / "DEPS")
    revisions = {"chromium": pins["chromium_commit"]}
    for name in ("skia", "dawn"):
        matches = re.findall(r"['\"]" + name + r"_revision['\"]\s*:\s*['\"]([0-9a-f]{40})['\"]", deps)
        if len(matches) != 1 or matches[0] == "0" * 40:
            raise ValueError(f"Cannot identify the pinned {name} revision in Chromium DEPS")
        revisions[name] = matches[0]
    return revisions


def valid_revision(value, expected):
    match = re.fullmatch(REVISION, value)
    return bool(match and match[1] == expected and expected != "0" * 40)


def valid_header(path, relative, macro, expected, revision_only=False):
    guard = relative.upper().replace("/", "_").replace(".", "_") + "_"
    contents = read(path)
    match = re.fullmatch(
        r"/\* Generated by lastchange\.py, do not edit\.\*/\n\n"
        + r"#ifndef " + re.escape(guard) + r"\n#define " + re.escape(guard) + r"\n\n"
        + r"#define " + macro + r' "([^"\n]+)"\n\n'
        + r"#endif  // " + re.escape(guard) + r"\n", contents)
    return bool(match and valid_revision(match[1], expected)
                and (not revision_only or match[1] == expected))


def valid_hook(root, hook):
    name, _, _, expected, outputs = hook
    if name == "gpu_lists_version":
        return valid_header(root / outputs[0], outputs[0], "GPU_LISTS_VERSION", expected, True)
    if name == "lastchange_skia":
        return valid_header(root / outputs[0], outputs[0], "SKIA_COMMIT_HASH", expected)
    if name == "lastchange_dawn":
        return valid_revision(read(root / outputs[0]), expected)
    match = re.fullmatch(r"LASTCHANGE=(\S+)\nLASTCHANGE_YEAR=([0-9]{4})\n", read(root / outputs[0]))
    timestamp = read(root / outputs[1])
    if not (match and valid_revision(match[1], expected) and "-" in match[1]
            and re.fullmatch(r"[1-9][0-9]*", timestamp)):
        return False
    try:
        return datetime.fromtimestamp(int(timestamp), timezone.utc).year == int(match[2])
    except (ValueError, OverflowError, OSError):
        return False


def hooks(source):
    revisions = expected_revisions(source)
    return (
        ("lastchange", source, (), revisions["chromium"],
         ("build/util/LASTCHANGE", "build/util/LASTCHANGE.committime")),
        ("gpu_lists_version", source, ("-m", "GPU_LISTS_VERSION", "--revision-id-only"),
         revisions["chromium"], ("gpu/config/gpu_lists_version.h",)),
        ("lastchange_skia", source / "third_party/skia", ("-m", "SKIA_COMMIT_HASH"),
         revisions["skia"], ("skia/ext/skia_commit_hash.h",)),
        ("lastchange_dawn", source / "third_party/dawn", (), revisions["dawn"],
         ("gpu/webgpu/DAWN_VERSION",)),
    )


def repair(source, hook):
    name, repo, options, _, outputs = hook
    # A source archive inside an unrelated Git checkout must not inherit that
    # checkout's revision. Worktree Git metadata must also be mounted/readable.
    result = subprocess.run(["git", "-C", str(repo), "rev-parse", "--show-toplevel"],
                            text=True, capture_output=True)
    if result.returncode or Path(result.stdout.strip()).resolve() != repo:
        raise ValueError(f"{name}: Git metadata is unavailable for {repo}. "
                         "Repair in the original workspace, or mount its Git metadata; "
                         "an existing valid cache can be used without Git.")
    env = os.environ.copy()
    env.pop("BASE_COMMIT_HASH", None)
    env.pop("BASE_COMMIT_SUBMISSION_MS", None)
    # Keep a src/ component so upstream GetHeaderGuard uses its normal guard.
    # Validate staged files before replacing anything: lastchange.py can return
    # success after falling back to an all-zero revision.
    with tempfile.TemporaryDirectory(prefix="electron-local-hooks-") as temporary:
        staged = Path(temporary) / "src"
        for output in outputs:
            (staged / output).parent.mkdir(parents=True, exist_ok=True)
        flag = "-o" if name == "lastchange" else (
            "--revision" if name == "lastchange_dawn" else "--header")
        command = [sys.executable, str(source / "build/util/lastchange.py"), *options]
        if repo != source:
            command.extend(("-s", str(repo)))
        command.extend((flag, str(staged / outputs[0])))
        print(f"Refreshing local DEPS hook: {name}", flush=True)
        subprocess.run(command, cwd=source, env=env, check=True)
        if not valid_hook(staged, hook):
            raise ValueError(f"{name}: upstream output is invalid or differs from its pinned revision; "
                             "original cached files were retained.")
        for output in outputs:
            destination = source / output
            contents = (staged / output).read_bytes()
            if not destination.is_file() or destination.read_bytes() != contents:
                destination.write_bytes(contents)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="Chromium src directory")
    parser.add_argument("--check-only", action="store_true", help="validate without repairing any files")
    args = parser.parse_args()
    source = args.source.expanduser().resolve()
    if not (source / "build/util/lastchange.py").is_file():
        parser.error("source must be an initialized Chromium src directory")
    pending = [hook for hook in hooks(source) if not valid_hook(source, hook)]
    if pending and args.check_only:
        raise ValueError("Missing or invalid local DEPS hook outputs: "
                         + ", ".join(hook[0] for hook in pending)
                         + ". Run this script without --check-only in a Git-visible workspace.")
    for hook in pending:
        repair(source, hook)
    print("Local DEPS version-hook outputs verified (5 files).", flush=True)


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        raise SystemExit(str(error))
