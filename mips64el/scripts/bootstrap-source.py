#!/usr/bin/env python3
"""Create an independent, pinned Electron checkout; never reset an existing tree.

This network bootstrap is experimental. It has not yet been validated by a
complete clean MIPS64EL Electron build. All paths are confined to WORKSPACE.
"""

import argparse
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
PINS = json.loads((ROOT / "metadata/source-pins.json").read_text())


def run(command, cwd, **kwargs):
    print("+ " + " ".join(map(str, command)), flush=True)
    return subprocess.run(list(map(str, command)), cwd=cwd, check=True, **kwargs)


def git_output(repo, *args):
    return subprocess.check_output(["git", "-C", str(repo), *args], text=True).strip()


def configuration():
    solution = {
        "name": "src/electron",
        "url": PINS["electron_url"] + "@" + PINS["electron_commit"],
        "deps_file": "DEPS",
        "managed": False,
        # Chromium 138 declares these as GCS deps as well as Electron hooks.
        # install_sysroot=False alone does not suppress those downloads.
        "custom_deps": {
            "src/build/linux/debian_bullseye_" + arch + "-sysroot": None
            for arch in ("amd64", "arm64", "armhf", "i386", "mips64el", "mipsel", "ppc64el")
        },
        "custom_vars": {
            "chromium_version": PINS["chromium_commit"],
            "checkout_configuration": "small",
            "checkout_js_coverage_modules": False,
            "checkout_pgo_profiles": False,
            "checkout_clang_tidy": False,
            "checkout_telemetry_dependencies": False,
            "checkout_instrumented_libraries": False,
            "install_sysroot": False,
            # Run official patches explicitly, with per-repository recovery state.
            "apply_patches": False,
            "use_mtime_cache": False,
        },
    }
    return (
        "# Generated by the MIPS64EL recipe; use a separate workspace.\n"
        + "solutions = " + repr([solution]) + "\n"
        + "target_os = ['linux']\n"
        # depot_tools spells this selector 'mips64', while GN uses 'mips64el'.
        + "target_cpu = ['x64', 'mips64']\n"
        # Keep optional user-wide Git caches out of this standalone checkout.
        + "cache_dir = None\n"
    )


def initialize(workspace, fetch_depot=True):
    workspace.mkdir(parents=True, exist_ok=True)
    marker = workspace / ".mips64el-source.json"
    config = workspace / ".gclient"
    if marker.exists():
        if json.loads(marker.read_text()) != PINS:
            raise SystemExit("Workspace source pins differ; select a new empty workspace.")
        if not config.exists() or config.read_text() != configuration():
            raise SystemExit("Workspace .gclient was changed; review it before resuming.")
    else:
        if any(workspace.iterdir()):
            raise SystemExit("Refusing to initialize a nonempty workspace without this recipe's marker.")
        config.write_text(configuration())
        marker.write_text(json.dumps(PINS, indent=2) + "\n")
    depot = workspace / "tools/depot_tools"
    if not depot.exists():
        depot.parent.mkdir(parents=True, exist_ok=True)
        run(["git", "init", depot], workspace)
    if not (depot / ".git").is_dir():
        raise SystemExit(f"Expected a dedicated depot_tools Git checkout: {depot}")
    # A previous interruption may have happened between git init and remote add.
    remote = subprocess.run(["git", "-C", str(depot), "remote", "get-url", "origin"],
                            text=True, capture_output=True)
    if remote.returncode:
        run(["git", "-C", depot, "remote", "add", "origin", PINS["depot_tools_url"]], workspace)
    elif remote.stdout.strip() != PINS["depot_tools_url"]:
        raise SystemExit("depot_tools origin differs from its pin; refusing to replace it.")
    if not fetch_depot:
        return depot
    head = subprocess.run(["git", "-C", str(depot), "rev-parse", "HEAD"],
                          text=True, capture_output=True)
    if head.returncode:
        run(["git", "-C", depot, "fetch", "--depth=1", "origin", PINS["depot_tools_commit"]], workspace)
        run(["git", "-C", depot, "checkout", "--detach", PINS["depot_tools_commit"]], workspace)
    elif head.stdout.strip() != PINS["depot_tools_commit"]:
        raise SystemExit("depot_tools HEAD differs from its pin; refusing to overwrite it.")
    return depot


def verify_hook_outputs(workspace):
    # These are normal DEPS/hook outputs, before applying local MIPS changes.
    # Checking them catches a partially copied cache that otherwise reaches GN.
    required = (
        "src/buildtools/linux64/gn",
        "src/third_party/rust-toolchain/bin/rustc",
        "src/electron/node_modules/.yarn-integrity",
        "src/gpu/webgpu/DAWN_VERSION",
        "src/third_party/dawn/third_party/khronos/OpenGL-Registry/xml/gl.xml",
        "src/third_party/dawn/third_party/khronos/EGL-Registry/api/egl.xml",
    )
    missing = [name for name in required
               if not (workspace / name).is_file() or (workspace / name).stat().st_size == 0]
    if missing:
        raise SystemExit("Required synced/hook inputs are missing: " + ", ".join(missing)
                         + ". Finish recursive sync and hooks in this workspace; "
                           "do not copy a partial source cache.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("workspace", type=Path,
                        help="a new directory, or a workspace created by this script")
    parser.add_argument("--stage", choices=("init", "sync", "patches", "hooks", "all"), default="all")
    parser.add_argument("--jobs", type=int, default=2)
    args = parser.parse_args()
    if args.jobs < 1:
        parser.error("--jobs must be positive")
    workspace = args.workspace.expanduser().resolve()
    depot = initialize(workspace, fetch_depot=args.stage != "init")
    os.environ["DEPOT_TOOLS_UPDATE"] = "0"
    os.environ["PATH"] = str(depot) + os.pathsep + os.environ["PATH"]
    gclient = depot / "gclient"
    if args.stage == "init":
        print(f"Initialized source configuration without network access: {workspace}")
        return
    stages = ("sync", "patches", "hooks") if args.stage == "all" else (args.stage,)
    for stage in stages:
        if stage == "sync":
            if (workspace / "logs/official-patches.json").exists():
                raise SystemExit(
                    "Official patch state already exists. Do not gclient-sync a patched tree; "
                    "resume --stage patches or --stage hooks, or use a new workspace."
                )
            run([gclient, "sync", "--no-history", "--shallow", "--nohooks", "--noprehooks",
                 "--jobs=" + str(args.jobs)], workspace)
            actual_electron = git_output(workspace / "src/electron", "rev-parse", "HEAD")
            actual_chromium = git_output(workspace / "src", "rev-parse", "HEAD")
            if (actual_electron, actual_chromium) != (PINS["electron_commit"], PINS["chromium_commit"]):
                raise SystemExit("Electron/Chromium revisions differ from the pinned manifest.")
            logs = workspace / "logs"
            logs.mkdir(exist_ok=True)
            run([gclient, "revinfo", "--actual", "--output-json=" + str(logs / "source-revisions.json")], workspace)
        elif stage == "patches":
            run([sys.executable, ROOT / "scripts/apply-official-patches.py", workspace], workspace)
        elif stage == "hooks":
            if not (workspace / "logs/official-patches.complete").exists():
                raise SystemExit("Apply the complete official patch stack before running hooks.")
            run([gclient, "runhooks", "--jobs=" + str(args.jobs)], workspace)
            verify_hook_outputs(workspace)
    print(f"Completed {args.stage} stage: {workspace}")
    print("Apply the local MIPS adaptations after hooks. A complete Electron build is still experimental.")


if __name__ == "__main__":
    main()
